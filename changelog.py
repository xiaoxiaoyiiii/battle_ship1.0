def view(limit: int = 10) -> dict:
    """给接口用的视图：截断 + **拷贝**（绝不把内部列表交给调用方）。

    ⚠️ 拷贝是必须的：`api.py` 拿去 `jsonify` 之后，只要有人往内部列表里 append，
    下一次响应就会带上别人的数据（本仓库"同一份数据被多处持有"栽过）。
    """
    try:
        n = int(limit)
    except (TypeError, ValueError):
        n = 10
    n = max(1, min(n, 20))          # 上限 20：公告是给人看的，不需要分页
    entries = [
        {'date': str(e.get('date') or ''), 'items': [str(x) for x in (e.get('items') or [])]}
        for e in CHANGELOG[:n]
    ]
    return {'latest': latest_date(), 'entries': entries}


def latest_date() -> str:
    """最新一条的时间（没有条目时返回空串）。

    前端拿它跟 `localStorage` 里存的"看过的最后时间"比：不一样就说明有新公告。
    """
    if not CHANGELOG:
        return ''
    return str(CHANGELOG[0].get('date') or '')
